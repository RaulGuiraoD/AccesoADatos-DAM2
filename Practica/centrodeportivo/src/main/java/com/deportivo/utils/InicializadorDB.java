package com.deportivo.utils;

import java.sql.Statement;
import java.sql.Connection;
import java.sql.SQLException;

public final class InicializadorDB {

    private InicializadorDB() {}

    public static void crearTablas() {
        String sql = "CREATE TABLE activdad ("
        + "id INTEGER PRIMARY KEY AUTOINCREMENT, "
        + "nombre TEXT NOT NULL, "
        + "plaza_disponibles INTEGER NOT NULL)";
        Connection con = ConnectToDB.getInstance().getConnection();

        try (Statement st = con.createStatement()) {
            st.execute(sql);
        } catch (SQLException e) {
            System.out.println("Aviso al crear tabla: " + e.getMessage());
        }
    }
    
}

